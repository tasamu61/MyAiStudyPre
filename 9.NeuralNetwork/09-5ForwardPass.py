# 09-5ForwardPass.py ― 入力（左端）から出力（右端）まで、値を計算して通す
# Python の標準ライブラリだけで動く（Colab でそのまま実行できる）

def relu(z):
    if z > 0:
        return z
    return 0.0


def show(name, values):          # 値を見やすく表示するだけの関数
    print(name, end=" = ")
    for v in values:
        print(f"{v:6.3f}", end="")
    print()


# 係数（学習で決まる数。ここでは適当な値を手で置く）
#   入力3個 → 隠れ層1：4個 → 隠れ層2：4個 → 出力2個
W1 = [[ 0.5, -1.0,  0.3],            # 隠れ層1：ニューロン4個 × 入力3個ぶんの重み
      [ 1.0,  0.2, -0.5],
      [-0.4,  0.8,  0.6],
      [ 0.7,  0.1, -0.9]]
b1 = [0.0, 0.1, -0.1, 0.2]           # 隠れ層1：ニューロンごとのずらし

W2 = [[ 0.5, -0.3,  0.8,  0.1],      # 隠れ層2：ニューロン4個 × 隠れ層1の4個ぶんの重み
      [-0.6,  0.4,  0.2,  0.9],
      [ 0.3,  0.3, -0.7,  0.5],
      [ 0.1, -0.8,  0.6,  0.2]]
b2 = [0.1, 0.0, -0.1, 0.2]

W3 = [[ 1.0, -0.5,  0.3,  0.8],      # 出力層：ニューロン2個 × 隠れ層2の4個ぶんの重み
      [-0.2,  0.7,  0.4, -0.6]]
b3 = [0.0, 0.1]


# 入力（絵の左端）
x = [1.0, 2.0, 0.5]
show("x ", x)

# 隠れ層1：4個のニューロンが、同じ入力 x を、別々の係数で計算する
h1 = [0.0, 0.0, 0.0, 0.0]
for j in range(4):
    z = b1[j]
    for i in range(3):
        z = z + W1[j][i] * x[i]      # 入力 × 重み を足す
    h1[j] = relu(z)                  # 活性化関数
show("h1", h1)

# 隠れ層2：4個のニューロンが、h1 の4個の出力を全部受け取る
h2 = [0.0, 0.0, 0.0, 0.0]
for j in range(4):
    z = b2[j]
    for i in range(4):
        z = z + W2[j][i] * h1[i]
    h2[j] = relu(z)
show("h2", h2)

# 出力層（絵の右端）：一次式だけ。活性化関数は挟まない
y = [0.0, 0.0]
for j in range(2):
    z = b3[j]
    for i in range(4):
        z = z + W3[j][i] * h2[i]
    y[j] = z
show("y ", y)
