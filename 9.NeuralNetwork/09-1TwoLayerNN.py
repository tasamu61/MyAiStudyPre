def relu(z):
    return np.maximum(z, 0)


# ------------------------------------
# (A) 5章と同じ、1層だけのモデル(比較用)
#     weightsは3x256, biasは3。ゼロ初期化でも、1層だけなら問題なく学習できる。
# ------------------------------------
def train_1layer(epochs=600, rate=0.01):
    W = np.zeros((3, 256))
    b = np.zeros(3)
    for epoch in range(epochs):
        prediction = X @ W.T + b
        diff = prediction - targets
        loss = np.sum(diff ** 2)
        gradient = 2 * diff
        W -= rate * (gradient.T @ X)
        b -= rate * np.sum(gradient, axis=0)
    return W, b, loss


# ------------------------------------
# (B) 隠れ層を1つ持つ2層モデル。
#     1層目: 256入力 -> H個の隠れユニット(ReLUで非線形変換)
#     2層目: H個の隠れユニット -> 3クラス分のスコア
#
#     順伝播:
#       Z1 = X  @ W1.T + b1   (15,256)@(256,H) -> (15,H)
#       A1 = relu(Z1)                           (15,H)
#       Z2 = A1 @ W2.T + b2   (15,H)@(H,3)     -> (15,3)
#
#     逆伝播(連鎖律を2層ぶん繋げるだけ。1章・5章と考え方は同じ):
#       dLoss/dZ2 = 2*(Z2-targets)                        … 5章と同じ式
#       dLoss/dW2 = dLoss/dZ2.T @ A1
#       dLoss/dA1 = dLoss/dZ2 @ W2                         … ここが新しい連鎖律の1段
#       dLoss/dZ1 = dLoss/dA1 * (Z1>0)                     … ReLUの微分(0か1)を掛けるだけ
#       dLoss/dW1 = dLoss/dZ1.T @ X
# ------------------------------------
def train_2layer(H=8, epochs=3000, rate=0.01, seed=0, zero_init=False):
    if zero_init:
        # わざと全部ゼロで初期化した場合(9.3.1で失敗例として使う)
        W1 = np.zeros((H, 256))
        W2 = np.zeros((3, H))
    else:
        rng = np.random.default_rng(seed)
        W1 = rng.normal(0, 0.1, size=(H, 256))
        W2 = rng.normal(0, 0.1, size=(3, H))
    b1 = np.zeros(H)
    b2 = np.zeros(3)

    for epoch in range(epochs):
        Z1 = X @ W1.T + b1
        A1 = relu(Z1)
        Z2 = A1 @ W2.T + b2

        diff = Z2 - targets
        loss = np.sum(diff ** 2)

        g2 = 2 * diff                      # dLoss/dZ2
        W2_grad = g2.T @ A1
        b2_grad = np.sum(g2, axis=0)

        dA1 = g2 @ W2                      # dLoss/dA1 (連鎖律)
        dZ1 = dA1 * (Z1 > 0)               # ReLUの微分(Z1>0なら1、そうでなければ0)
        W1_grad = dZ1.T @ X
        b1_grad = np.sum(dZ1, axis=0)

        W1 -= rate * W1_grad; b1 -= rate * b1_grad
        W2 -= rate * W2_grad; b2 -= rate * b2_grad

    return W1, b1, W2, b2, loss


def predict_1layer(Xq, W, b):
    return np.argmax(Xq @ W.T + b, axis=1)


def predict_2layer(Xq, W1, b1, W2, b2):
    return np.argmax(relu(Xq @ W1.T + b1) @ W2.T + b2, axis=1)


def report(title, pred_train, pred_eval):
    print(f"\n[{title}]")
    print(f"  学習データ正解数: {(pred_train == y).sum()} / {len(y)}")
    print(f"  評価データ正解数: {(pred_eval == ye).sum()} / {len(ye)}")
    for name, p, t in zip(names_e, pred_eval, ye):
        mark = "OK" if p == t else "NG"
        print(f"    {name:8s} 予測={p} 正解={t}  {mark}")


