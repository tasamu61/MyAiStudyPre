def to_bits(rows):
    return [1.0 if ch == "1" else 0.0 for row in rows for ch in row]


X = np.array([to_bits(rows) for _, rows in TRAINING_RAW])          # (15, 256)
y = np.array([int(name[0]) for name, _ in TRAINING_RAW])           # (15,)   正解クラス(0,1,2)
targets = np.zeros((len(TRAINING_RAW), 3))
for i, c in enumerate(y):
    targets[i, c] = 1.0                                            # one-hot (15, 3)

Xe = np.array([to_bits(rows) for _, rows in EVAL_RAW])             # (6, 256)
